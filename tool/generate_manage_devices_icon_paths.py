"""Extract Manage Devices icon outlines from the already bundled Material Symbols font.

Requires fontTools and brotli. Run from the energylens-mobile directory.
"""

import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/design_pages/shared/fonts/kJEhBvYX7BgnkSrUwT8OhrdQw4oELdPIeeII9v6oFsLjBuVY.woff2"
OUTPUT = ROOT / "assets/design_pages/shared/manage_devices_icon_paths.js"
TOKENS = (
    "add", "arrow_drop_down", "badge", "bolt", "category", "check",
    "check_circle", "computer", "delete", "delete_outline", "desktop_windows",
    "devices", "devices_other", "document_scanner", "edit_note",
    "energy_savings_leaf", "hub", "kitchen", "lightbulb",
    "local_laundry_service", "mode_fan", "more_horiz", "person",
    "photo_camera", "post_add", "radar", "router", "savings", "settings",
    "skillet", "space_dashboard", "speaker", "thermostat", "tune", "tv",
    "upload_file", "water_heater", "wifi_find",
)


def ligature_glyphs(font):
    reverse = {glyph: chr(codepoint) for codepoint, glyph in font.getBestCmap().items()}
    result = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for subtable in lookup.SubTable:
            table = subtable.ExtSubTable if lookup.LookupType == 7 else subtable
            for start, ligatures in getattr(table, "ligatures", {}).items():
                for ligature in ligatures:
                    token = "".join(reverse.get(glyph, "") for glyph in (start, *ligature.Component))
                    if token in TOKENS:
                        result[token] = ligature.LigGlyph
    missing = sorted(set(TOKENS) - set(result))
    if missing:
        raise ValueError(f"Missing Material Symbols ligatures: {missing}")
    return result


def main():
    font = TTFont(FONT)
    units = font["head"].unitsPerEm
    glyphs = ligature_glyphs(font)
    outlines = {}
    for weight in (400, 700):
        variants = {}
        for fill in (0, 1):
            instance = instantiateVariableFont(font, {"FILL": fill, "GRAD": 0, "opsz": 24, "wght": weight})
            glyph_set = instance.getGlyphSet()
            paths = {}
            for token in TOKENS:
                pen = SVGPathPen(glyph_set)
                glyph_set[glyphs[token]].draw(TransformPen(pen, (1, 0, 0, -1, 0, units)))
                paths[token] = pen.getCommands()
            variants[str(fill)] = paths
        outlines[str(weight)] = variants
    data = json.dumps({"viewBox": f"0 0 {units} {units}", "paths": outlines}, sort_keys=True, separators=(",", ":"))
    OUTPUT.write_text("/* Generated by tool/generate_manage_devices_icon_paths.py from the bundled font. */\n" +
                      "window.EnergyLensManageDevicesIconPaths = " + data + ";\n")


if __name__ == "__main__":
    main()
